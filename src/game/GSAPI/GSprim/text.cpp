static f32 _primTextXpel = 6.0f;
static f32 _primTextYpel = 6.0f;
static GSgfxColAu8 _primTextColor = {255, 255, 255, 255};

u32 _primRenderBuf(f32 x, f32 y, char *str, u32 len, bool emit);
u8 *_primChar2Ptr(char c);

void GSprimWriteStr(f32 x, f32 y, const char *format, ...)
{
    static char buf[256];
    va_list args;
    va_start(args, format);
    vsprintf(buf, format, args);
    va_end(args);
    u32 len = strlen(buf);

    if (primData.linePushMode != 2) {
        GSprimLayerLineWidth(primData.layer, (u8)(6.0f * primData.textWidth));
        primData.linePushMode = 2;
    }
    primData.layer->setRenderStateAndSelect(GSgfxVFGetPredef(2));
    primData.layer->mPrimitiveType = (GSgfxPrimType)GSprimPrimLines;
    u32 n = _primRenderBuf(x, y, buf, len, false);
    primData.layer->beginSurface((u16)(n * 2));
    _primRenderBuf(x, y, buf, len, true);
    primData.layer->endSurface();
}

void GSprimWriteChar(f32 x, f32 y, char c)
{
    if (primData.linePushMode != 2) {
        GSprimLayerLineWidth(primData.layer, (u8)(6.0f * primData.textWidth));
        primData.linePushMode = 2;
    }
    primData.layer->setRenderStateAndSelect(GSgfxVFGetPredef(2));
    primData.layer->mPrimitiveType = (GSgfxPrimType)GSprimPrimLines;
    u32 n = _primRenderBuf(x, y, &c, 1, false);
    primData.layer->beginSurface((u16)(n * 2));
    _primRenderBuf(x, y, &c, 1, true);
    primData.layer->endSurface();
}

void GSprimSetTextWidth(f32 width)
{
    primData.textWidth = width;
    primData.linePushMode = 0;
}

void GSprimSetTextColor(GSgfxColAu8 color)
{
    _primTextColor = color;
}

void GSprimSetTextSize(f32 width, f32 height)
{
    _primTextXpel = width;
    _primTextYpel = height;
}

static inline u8 _primHexDigit(char d)
{
    switch (d) {
    case '0': case '1': case '2': case '3': case '4':
    case '5': case '6': case '7': case '8': case '9':
        return d - '0';
    case 'a': case 'b': case 'c': case 'd': case 'e': case 'f':
        return d - ('a' - 10);
    case 'A': case 'B': case 'C': case 'D': case 'E': case 'F':
        return d - ('A' - 10);
    default:
        return 0;
    }
}

u32 _primRenderBuf(f32 x, f32 y, char *str, u32 len, bool emit)
{
    u32 total = 0;
    char *p = str;
    GSgfxColAu8 color;
    int count;

    while (len-- > 0) {
        char c = *p;
        switch (c) {
        case '\r':
        case '\n':
            break;
        case '|':
            if (emit == 1) {
                u8 hi, lo;
                hi = _primHexDigit(p[1]);
                lo = _primHexDigit(p[2]);
                _primTextColor.r = (hi << 4) | lo;
                hi = _primHexDigit(p[3]);
                lo = _primHexDigit(p[4]);
                _primTextColor.g = (hi << 4) | lo;
                hi = _primHexDigit(p[5]);
                lo = _primHexDigit(p[6]);
                _primTextColor.b = (hi << 4) | lo;
            }
            len -= 6;
            p += 6;
            break;
        default: {
            u8 *rec = _primChar2Ptr(c);
            count = *rec++;
            total += count;
            if (emit == 1) {
                f32 xpel = _primTextXpel;
                f32 ypel = _primTextYpel;
                color = _primTextColor;
                while (count-- != 0) {
                    GSvec2 v0, v1;
                    f32 sx, sy;
                    sx = 0.11f * (rec[0] >> 4);
                    sy = 0.11f * (rec[0] & 15);
                    v0.x = x + sx * xpel;
                    v0.y = y + sy * ypel;
                    sx = 0.11f * (rec[1] >> 4);
                    sy = 0.11f * (rec[1] & 15);
                    v1.x = x + sx * xpel;
                    v1.y = y + sy * ypel;
                    rec += 2;
                    GSgfxFifo.f32 = v0.x;
                    GSgfxFifo.f32 = v0.y;
                    GSgfxFifo.u8 = color.r;
                    GSgfxFifo.u8 = color.g;
                    GSgfxFifo.u8 = color.b;
                    GSgfxFifo.u8 = color.a;
                    GSgfxFifo.f32 = v1.x;
                    GSgfxFifo.f32 = v1.y;
                    GSgfxFifo.u8 = color.r;
                    GSgfxFifo.u8 = color.g;
                    GSgfxFifo.u8 = color.b;
                    GSgfxFifo.u8 = color.a;
                }
            }
        case ' ':
            x += _primTextXpel;
            break;
        }
        }
        p++;
    }
    return total;
}

u8 *_primChar2Ptr(char c)
{
    u32 row;

    if (c >= '0' && c <= '9')
        row = c - '0';
    else if (c >= 'A' && c <= 'Z')
        row = c - 'A' + 10;
    else if (c >= 'a' && c <= 'z')
        row = c - 'a' + 10;
    else {
        switch (c) {
        case '-':
            row = 36;
            break;
        case '_':
            row = 37;
            break;
        case '~':
            row = 38;
            break;
        case '>':
            row = 39;
            break;
        case '/':
            row = 40;
            break;
        case '(':
            row = 41;
            break;
        case ')':
            row = 42;
            break;
        case ',':
            row = 43;
            break;
        case '<':
            row = 44;
            break;
        case '+':
            row = 45;
            break;
        case '$':
            row = 46;
            break;
        case '.':
            row = 47;
            break;
        case ':':
            row = 48;
            break;
        case '[':
            row = 49;
            break;
        case ']':
            row = 50;
            break;
        case '=':
            row = 51;
            break;
        case '#':
            row = 52;
            break;
        case '!':
            row = 53;
            break;
        case '\'':
            row = 54;
            break;
        case '"':
            row = 55;
            break;
        default:
            row = 37;
            break;
        }
    }
    return _primLineFont[row];
}
